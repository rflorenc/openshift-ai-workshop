#!/usr/bin/env bash
# build.sh [build|serve|publish]: the workshop website from the participant guides.
#   build (default)  regenerate docs/ and build the static site into site/ (for GitHub Pages or any web server)
#   serve            regenerate docs/ and serve it on http://127.0.0.1:8000 with live reload of src/ changes
#   publish          regenerate, commit the source to main, push, deploy site/ to gh-pages
#                    (live at https://rflorenc.github.io/openshift-ai-workshop/ after a minute)
#
# Source of truth: ../lab-setup/labs/<day>/<lab>/guide (listed in labs.yaml) + src/ (start page, credits,
# style, placeholder script). docs/ is generated: never edit it. MkDocs Material runs in a venv outside
# the repo (~/.config/workshop-site/venv).
set -euo pipefail
cd "$(dirname "$0")"
MODE=${1:-build}
VENV=${VENV:-$HOME/.config/workshop-site/venv}
if [ ! -x "$VENV/bin/mkdocs" ]; then
  echo "== installing MkDocs Material into $VENV"
  python3 -m venv "$VENV" && "$VENV/bin/pip" install -q --upgrade pip && "$VENV/bin/pip" install -q "mkdocs-material>=9.5,<10" pyyaml
fi

"$VENV/bin/python" - <<'EOF'
import re, shutil, pathlib, yaml
here = pathlib.Path('.'); labs_root = pathlib.Path('../lab-setup/labs')
docs = here / 'docs'
shutil.rmtree(docs, ignore_errors=True)
shutil.copytree(here / 'src', docs)
cfg = yaml.safe_load(open('labs.yaml'))
SKIP = {'_sidebar.md', 'index.html', '.nojekyll', 'LICENSE'}
CHIP = {'lab': 'Lab', 'activity': 'Activity', 'demo': 'Demo', 'slides': 'Slides'}

def h1(p):
    for line in p.read_text(encoding='utf-8').splitlines():
        if line.startswith('# '): return line[2:].strip()
    return p.stem

def nested(guide, base):
    """Rebuild sidebar into MkDocs nav: sections for entries with children."""
    nodes = []
    for line in (guide / '_sidebar.md').read_text(encoding='utf-8').splitlines():
        m = re.match(r'^(\s*)\*\s*\[(.+?)\]\((.+?)\)', line)
        if m:
            t = m.group(3)
            t = 'index.md' if t in ('/', '') else re.sub(r'(^|/)README\.md$', r'\1index.md', t.lstrip('/'))
            nodes.append((len(m.group(1)), m.group(2), f'{base}/{t}'))
    def take(i, depth):
        out = []
        while i < len(nodes) and nodes[i][0] == depth:
            _, title, path = nodes[i]; i += 1
            if i < len(nodes) and nodes[i][0] > depth:
                kids, i = take(i, nodes[i][0])
                out.append({title: [path] + kids})
            else:
                out.append({title: path})
        return out, i
    nav, _ = take(0, nodes[0][0] if nodes else 0)
    return nav

nav = [{'Home': 'index.md'}]
for day in cfg['days']:
    day_dir = docs / day['slug']; day_dir.mkdir(parents=True)
    day_nav = [f"{day['slug']}/index.md"]
    cards = []
    for lab in day['labs']:
        guide = labs_root / lab['src'] / 'guide'
        dst = day_dir / lab['slug']
        shutil.copytree(guide, dst, ignore=lambda d, names: [n for n in names if n in SKIP])
        base = f"{day['slug']}/{lab['slug']}"
        for md in dst.rglob('*.md'):
            s = md.read_text(encoding='utf-8')
            s = re.sub(r'\]\((\.?/?)README\.md', r'](\1index.md', s)                 # [x](README.md)
            s = re.sub(r'\]\(([^)\s]*?/)README\.md', r'](\1index.md', s)              # [x](dir/README.md)
            s = re.sub(r"(\]\([^)\s]+?)\s+':[^']*'\)", r'\1)', s)                    # docsify ':size=60%' image options
            md.write_text(s, encoding='utf-8')
            if md.name == 'README.md': md.rename(md.with_name('index.md'))
        start = dst / 'index.md'
        chip = f'<span class="chip {lab["type"]}">{CHIP[lab["type"]]} · {lab["minutes"]} min</span>'
        lines = start.read_text(encoding='utf-8').split('\n')
        i = next((k for k, l in enumerate(lines) if l.startswith('# ')), -1)
        lines.insert(i + 1, '\n' + chip + '\n')
        start.write_text('\n'.join(lines), encoding='utf-8')
        if (guide / '_sidebar.md').exists():
            lab_nav = nested(guide, base)
            first = lab_nav[0]
            if isinstance(first, dict) and list(first.values())[0] == f'{base}/index.md':
                lab_nav[0] = f'{base}/index.md'
        else:
            pages = sorted(p for p in dst.glob('*.md') if p.name != 'index.md')
            lab_nav = [f'{base}/index.md'] + [f'{base}/{p.name}' for p in pages]
        day_nav.append({lab['nav']: lab_nav})
        cards.append(f'<div class="ws-card" markdown>\n{chip}\n### [{lab["nav"]}]({lab["slug"]}/index.md)\n{h1(start)}\n</div>')
    (day_dir / 'index.md').write_text(
        f"# {day['title']}: {day['subtitle']}\n\n<div class=\"ws-grid\" markdown>\n" + '\n'.join(cards) + '\n</div>\n',
        encoding='utf-8')
    nav.append({day['title']: day_nav})
nav.append({'Credits': 'credits.md'})
open('mkdocs.gen.yml', 'w').write('# generated by build.sh — do not edit\nINHERIT: mkdocs.yml\n' + yaml.safe_dump({'nav': nav}, sort_keys=False, allow_unicode=True))
print(f"== docs/ generated: {sum(1 for _ in docs.rglob('*.md'))} pages")
EOF

case "$MODE" in
  serve) exec "$VENV/bin/mkdocs" serve -f mkdocs.gen.yml ;;
  build) "$VENV/bin/mkdocs" build -f mkdocs.gen.yml --clean 2>&1 | grep -v -E "^INFO +-  (Cleaning|Building|Documentation built)" || true
         echo "== site/ built: open site/index.html, or ./build.sh serve" ;;
  publish)
    git add -A
    git diff --cached --quiet || git commit -q -m "Update guides"
    git push -q origin main
    NO_MKDOCS_2_WARNING=1 "$VENV/bin/mkdocs" gh-deploy -f mkdocs.gen.yml --force --message "Publish site" 2>&1 | grep -E "ERROR|available at" || true ;;
  *) echo "usage: build.sh [build|serve|publish]"; exit 2 ;;
esac
